-- ── zorlayıcı yapı ────────────────────────────────────────────────────────────────────────────────────────────────────
create unlogged table public.kz_gecici (id int primary key, metin text collate "C");
create table public.kz_tablo (
  id bigint generated by default as identity (start with 100 increment by 5) primary key,
  kod text not null unique,
  ad text collate "C",
  adet int default 1,
  iki_kat int generated always as (adet * 2) stored,
  cari_id text references public.cariler (id),
  notlar text
);
alter table public.kz_tablo add constraint kz_adet_pozitif check (adet > 0) not valid;
alter table public.kz_tablo replica identity full;
create sequence public.kz_sira as integer increment by 3 minvalue 7 maxvalue 99999 start with 10 cache 2 cycle;
create table public.kz_seri (id serial primary key, x text);
-- birbirine bağlı görünüm zinciri (alfabetik sıranın TERSİ: önce "kz_v_b"ye bağlı "kz_v_a" kurulmalı)
create view public.kz_v_b with (security_invoker = true) as select id, kod, adet from public.kz_tablo where adet > 0;
create view public.kz_v_a as select id, kod from public.kz_v_b with cascaded check option;
-- gövdesinde tek tırnak, dolar, çift dolar, "--" ile başlayan satır, boş satırlar, ters bölü olan fonksiyonlar; SQL fonksiyonu
-- alfabetik olarak SONRA gelen fonksiyonu çağırır (anada önce çağrılan kurulur; üretici alfabetik yazar → gövde denetimi açık
-- olsaydı yeni projede kurulamazdı)
create function public.kz_z_cagrilan(x int) returns int language sql immutable as $f$ select $1 * 10 $f$;
create function public.kz_a_cagiran(x int) returns int language sql stable as $f$ select public.kz_z_cagrilan($1) + 1 $f$;
create function public.kz_metin() returns text language plpgsql immutable as $g$
declare
  a text := 'tek '' tırnak';

  -- yorum satırı (Editor temizliği gövdeye dokunmamalı)


  b text := '$ ve $$ ve $1 ve \n ters bölü';
begin
  return a || ' | ' || b;
end
$g$;
create function public.kz_tetik() returns trigger language plpgsql as $f$ begin return new; end $f$;
create trigger kz_kapali before update on public.kz_tablo for each row execute function public.kz_tetik();
alter table public.kz_tablo disable trigger kz_kapali;
create trigger kz_her_zaman before insert on public.kz_tablo for each row execute function public.kz_tetik();
alter table public.kz_tablo enable always trigger kz_her_zaman;
alter table public.kz_tablo enable row level security;
alter table public.kz_tablo force row level security;
create policy kz_herkes_okur on public.kz_tablo for select to public using (true);
create policy kz_kisit on public.kz_tablo as restrictive for all to authenticated using (adet < 1000) with check (adet < 1000);
create policy kz_yaz on public.kz_tablo for insert to authenticated, anon with check (kod <> '');
revoke all on public.kz_tablo from anon, authenticated, service_role;
grant select on public.kz_tablo to authenticated with grant option;
grant update (notlar), insert (kod, adet) on public.kz_tablo to authenticated;
grant select (id, kod) on public.kz_tablo to anon;
grant usage, select on sequence public.kz_sira to anon;
revoke execute on function public.kz_metin() from public;
grant execute on function public.kz_metin() to anon;
do $d$ begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then create publication supabase_realtime; end if;
end $d$;
alter publication supabase_realtime add table public.kz_tablo, public.cariler;

