-- =====================================================================================
--  kurulum-betigi.sql — YENİ FİRMA KURULUM DOSYASINI ÜRETEN FONKSİYON (v1.642.0)
-- =====================================================================================
--
--  NEDEN: uygulama birden çok firmaya satılacak ve her firmanın AYRI Supabase projesi olacak. Yeni projede
--  tabloların, kuralların (RLS), tetikleyicilerin ve yetkilerin BUGÜNKÜ hâli birebir kurulmalı. Şemanın ilk
--  kurulum dosyaları (supabase-sema.sql, muhasebe-tablosu.sql…) depoda yok; sonradan eklenen onlarca SQL de
--  ayrı ayrı çalıştırıldı. En güvenilir kaynak çalışan veritabanının KENDİSİ: bu fonksiyon onu okuyup tek bir
--  kurulum betiği (metin) üretir. Uygulamada Tanımlar › Yedek & Bulut › "Yeni firma kurulum dosyasını indir"
--  bunu çağırır (yalnız Yönetici).
--
--  ÜRETİLEN BETİK (yeni, BOŞ projede SQL Editor'da bir kez çalıştırılır):
--    1. public şemasındaki diziler (sequence)
--    2. tablolar — sütun, tip, varsayılan, NOT NULL, identity / generated
--    3. birincil anahtar, tekil, kontrol kısıtları; sonra yabancı anahtarlar
--    4. kısıt dışı indeksler
--    5. fonksiyonlar (eklentilere ait olanlar hariç) — bu fonksiyonun kendisi de dahil
--    6. tetikleyiciler
--    7. RLS açık/zorunlu bayrakları + politikalar
--    8. anon / authenticated yetkileri (tablo, dizi, fonksiyon) — önce hepsi alınır, sonra bugünkü hâl verilir
--  VERİ YOK — yalnız yapı. İlk yönetici kaydı ayrıca (yeni-firma-kurulum.md, adım 4).
--
--  KULLANIM (bir kez, ANA projede): Supabase > SQL Editor > bu dosyanın tamamı > Run.
--  Tekrar çalıştırmak zararsız (create or replace).
-- =====================================================================================

create or replace function public.kurulum_betigi()
returns text
language plpgsql
stable
security definer
set search_path = public, pg_catalog
as $kb$
declare
  cikti text := '';
  r record;
  sutunlar text;
  rol text;
begin
  -- Yalnız Yönetici (ya da SQL Editor / servis rolü: jwt boş). Betik şemayı ve kuralları açık eder; sıradan
  -- kullanıcının bunu görmesine gerek yok.
  if auth.jwt() is not null and not public.yonetici_mi() then
    raise exception 'Kurulum dosyasını yalnız Yönetici indirebilir' using errcode = '42501';
  end if;

  cikti := cikti || '-- Atölye ERP — yeni firma kurulum betiği' || E'\n'
    || '-- Üretildi: ' || to_char(now(), 'YYYY-MM-DD HH24:MI') || E'\n'
    || '-- Yeni ve BOŞ bir Supabase projesinde SQL Editor > Run. Veri içermez, yalnız yapı.' || E'\n\n'
    || 'begin;' || E'\n\n';

  -- 1) Diziler
  for r in
    select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'S'
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')   -- identity dizileri tabloyla gelir
    order by c.relname
  loop
    cikti := cikti || format('create sequence if not exists public.%I;', r.relname) || E'\n';
  end loop;

  -- 2) Tablolar
  for r in
    select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r', 'p')
      and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'e')
    order by c.relname
  loop
    select string_agg(
      format('  %I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
             when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
             else '' end
        || case when a.attnotnull and a.attidentity = '' then ' not null' else '' end,
      E',\n' order by a.attnum)
    into sutunlar
    from pg_attribute a
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped;
    cikti := cikti || E'\n' || format('create table if not exists public.%I (', r.relname) || E'\n'
      || coalesce(sutunlar, '') || E'\n);\n';
  end loop;

  -- 2b) serial dizileri sütuna bağlı (sütun silinince dizi de gitsin — kaynaktaki gibi)
  for r in
    select s.relname as dizi, t.relname as tablo, a.attname as sutun
    from pg_depend d join pg_class s on s.oid = d.objid and s.relkind = 'S'
    join pg_class t on t.oid = d.refobjid join pg_namespace n on n.oid = t.relnamespace
    join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
    where d.deptype = 'a' and n.nspname = 'public'
  loop
    cikti := cikti || format('alter sequence public.%I owned by public.%I.%I;', r.dizi, r.tablo, r.sutun) || E'\n';
  end loop;

  -- 3) Kısıtlar: önce p/u/c, sonra f (yabancı anahtar öbür tablonun var olmasını ister). Var olan kısıt atlanır.
  for r in
    select con.conname, cl.relname, pg_get_constraintdef(con.oid) as tanim, con.contype
    from pg_constraint con join pg_class cl on cl.oid = con.conrelid join pg_namespace n on n.oid = cl.relnamespace
    where n.nspname = 'public' and con.contype in ('p', 'u', 'c', 'f', 'x')
    order by case con.contype when 'f' then 1 else 0 end, cl.relname, con.conname
  loop
    cikti := cikti || format(E'do $do$ begin alter table public.%I add constraint %I %s; exception when duplicate_object or duplicate_table or invalid_table_definition then null; end $do$;\n',
      r.relname, r.conname, r.tanim);
  end loop;

  -- 4) Kısıta bağlı olmayan indeksler
  for r in
    select pg_get_indexdef(i.indexrelid) as tanim
    from pg_index i join pg_class ic on ic.oid = i.indexrelid join pg_class tc on tc.oid = i.indrelid
    join pg_namespace n on n.oid = tc.relnamespace
    where n.nspname = 'public'
      and not exists (select 1 from pg_constraint con where con.conindid = i.indexrelid)
    order by ic.relname
  loop
    cikti := cikti || regexp_replace(r.tanim, '^CREATE (UNIQUE )?INDEX ', 'CREATE \1INDEX IF NOT EXISTS ') || E';\n';
  end loop;

  -- 5) Fonksiyonlar (eklentiye ait olanlar hariç)
  for r in
    select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
    order by p.proname
  loop
    cikti := cikti || E'\n' || pg_get_functiondef(r.oid) || E';\n';
  end loop;

  -- 6) Tetikleyiciler
  for r in
    select t.tgname, c.relname, pg_get_triggerdef(t.oid) as tanim
    from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal
    order by c.relname, t.tgname
  loop
    cikti := cikti || E'\n' || format('drop trigger if exists %I on public.%I;', r.tgname, r.relname) || E'\n' || r.tanim || E';\n';
  end loop;

  -- 7) RLS bayrakları + politikalar
  cikti := cikti || E'\n';
  for r in
    select c.relname, c.relrowsecurity, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind in ('r', 'p') and (c.relrowsecurity or c.relforcerowsecurity)
    order by c.relname
  loop
    if r.relrowsecurity then cikti := cikti || format('alter table public.%I enable row level security;', r.relname) || E'\n'; end if;
    if r.relforcerowsecurity then cikti := cikti || format('alter table public.%I force row level security;', r.relname) || E'\n'; end if;
  end loop;
  for r in
    select * from pg_policies where schemaname = 'public' order by tablename, policyname
  loop
    cikti := cikti || format('drop policy if exists %I on public.%I;', r.policyname, r.tablename) || E'\n'
      || format('create policy %I on public.%I as %s for %s to %s', r.policyname, r.tablename, lower(r.permissive), lower(r.cmd),
           (select string_agg(case when x = 'public' then 'public' else quote_ident(x) end, ', ') from unnest(r.roles) x))
      || case when r.qual is not null then ' using (' || r.qual || ')' else '' end
      || case when r.with_check is not null then ' with check (' || r.with_check || ')' else '' end
      || E';\n';
  end loop;

  -- 8) Yetkiler. Supabase yeni tabloya anon/authenticated için varsayılan yetki veriyor; bugünkü hâl (ör. anon'dan
  -- her şey alınmış — rls-kimlik.sql) aynen kurulsun diye önce HEPSİ alınır, sonra yalnız bugün olanlar verilir.
  cikti := cikti || E'\n' || 'revoke all on all tables in schema public from anon, authenticated;' || E'\n'
    || 'revoke all on all sequences in schema public from anon, authenticated;' || E'\n'
    || 'revoke all on all functions in schema public from public, anon, authenticated;' || E'\n';
  for r in
    select c.relname, c.relkind, acl.privilege_type, case when acl.grantee = 0 then 'public' else pg_get_userbyid(acl.grantee) end as kime
    from pg_class c join pg_namespace n on n.oid = c.relnamespace, lateral aclexplode(c.relacl) acl
    where n.nspname = 'public' and c.relkind in ('r', 'p', 'S', 'v')
      and (acl.grantee = 0 or pg_get_userbyid(acl.grantee) in ('anon', 'authenticated'))
    order by c.relname, kime, acl.privilege_type
  loop
    cikti := cikti || format('grant %s on %s public.%I to %s;', lower(r.privilege_type),
      case when r.relkind = 'S' then 'sequence' else 'table' end, r.relname, case when r.kime = 'public' then 'public' else quote_ident(r.kime) end) || E'\n';
  end loop;
  for r in
    select p.oid, p.proacl from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f', 'p')
      and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
  loop
    if r.proacl is null then
      -- Varsayılan: PUBLIC çalıştırabilir.
      cikti := cikti || format('grant execute on function %s to public;', r.oid::regprocedure) || E'\n';
    else
      for rol in
        select case when acl.grantee = 0 then 'public' else quote_ident(pg_get_userbyid(acl.grantee)) end
        from aclexplode(r.proacl) acl
        where acl.privilege_type = 'EXECUTE' and (acl.grantee = 0 or pg_get_userbyid(acl.grantee) in ('anon', 'authenticated'))
      loop
        cikti := cikti || format('grant execute on function %s to %s;', r.oid::regprocedure, rol) || E'\n';
      end loop;
    end if;
  end loop;

  -- 8b) VARSAYILAN YETKİLER (ileride açılacak tablolar): rls-kimlik.sql anon'dan kaldırıyor. Yalnız betiği çalıştıracak
  -- rolün (SQL Editor'da postgres) kayıtları taşınır; supabase_admin'inkileri postgres değiştiremez.
  for r in
    select d.defaclobjtype as tur, d.defaclacl as acl from pg_default_acl d join pg_namespace n on n.oid = d.defaclnamespace
    where n.nspname = 'public' and pg_get_userbyid(d.defaclrole) = 'postgres' and d.defaclobjtype in ('r', 'S', 'f')
  loop
    cikti := cikti || format('alter default privileges for role postgres in schema public revoke all on %s from anon, authenticated;',
      case r.tur when 'r' then 'tables' when 'S' then 'sequences' else 'functions' end) || E'\n';
    for rol in
      select format('alter default privileges for role postgres in schema public grant %s on %s to %s;',
        string_agg(lower(acl.privilege_type), ', '), case r.tur when 'r' then 'tables' when 'S' then 'sequences' else 'functions' end,
        quote_ident(pg_get_userbyid(acl.grantee)))
      from aclexplode(r.acl) acl where pg_get_userbyid(acl.grantee) in ('anon', 'authenticated')
      group by acl.grantee
    loop
      cikti := cikti || rol || E'\n';
    end loop;
  end loop;

  cikti := cikti || E'\ncommit;\n';
  return cikti;
end $kb$;

revoke all on function public.kurulum_betigi() from public, anon;
grant execute on function public.kurulum_betigi() to authenticated;
